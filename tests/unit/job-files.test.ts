import { describe, expect, it } from "vitest";
import { createHash } from "node:crypto";
import { parseGcode, parseStl, validateJobFiles } from "@/lib/files";
import { DEFAULT_FILE_POLICY } from "@/lib/machines/filePolicy";

const policy = { ...DEFAULT_FILE_POLICY, extensions: ["stl", "3mf", "zip", "step", "stp", "pdf", "png", "jpg", "jpeg", "webp", "gcode", "gco", "txt"] };
const validate = (filename: string, body: Uint8Array | string) => validateJobFiles([{ filename, body: typeof body === "string" ? Buffer.from(body) : body }], policy)[0];
const ascii = "solid test\nfacet normal 0 0 1\nouter loop\nvertex -1 2 0\nvertex 3 0 2\nvertex 0 4 -3\nendloop\nendfacet\nendsolid test\n";
function binary() {
  const bytes = Buffer.alloc(134);
  bytes.write("solid binary header"); bytes.writeUInt32LE(1, 80);
  [-1, 2, 0, 3, 0, 2, 0, 4, -3].forEach((n, i) => bytes.writeFloatLE(n, 96 + 4 * i));
  return bytes;
}

describe("job file policy and signatures", () => {
  it("enforces required, count, size, extension and case-insensitive extensions", () => {
    expect(() => validateJobFiles([], { ...policy, required: true })).toThrow("requires a file");
    expect(() => validateJobFiles([{ filename: "a.txt", body: Buffer.from("a") }], { ...policy, maxFiles: 0 })).toThrow("Too many");
    expect(() => validate("test.exe", "hello")).toThrow("extension");
    expect(() => validate("empty.txt", "")).toThrow("empty");
    expect(() => validateJobFiles([{ filename: "large.txt", body: Buffer.alloc(1025) }], { ...policy, maxBytes: 1024 })).toThrow("size limit");
    expect(validate("MODEL.STL", binary()).metadata).toMatchObject({ triangleCount: 1 });
  });
  it.each(["3mf", "zip"])("checks %s ZIP magic", (ext) => {
    expect(validate(`model.${ext}`, Buffer.from([80, 75, 3, 4])).extension).toBe(ext);
    expect(() => validate(`model.${ext}`, "PK invalid")).toThrow("ZIP");
  });
  it.each(["step", "stp"])("requires ISO-10303 in %s", (ext) => {
    expect(validate(`part.${ext}`, "ISO-10303-21;HEADER;").sizeBytes).toBeGreaterThan(0);
    expect(() => validate(`part.${ext}`, "not a STEP")).toThrow("STEP");
  });
  it("checks PDF and image signatures and blocks mismatches even under an allowlisted extension", () => {
    const samples = [Buffer.from("%PDF-1.7"), Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), Buffer.from([255, 216, 255, 0]), Buffer.from("RIFF1234WEBP")];
    samples.forEach((sample, i) => {
      expect(validate(`valid.${["pdf", "png", "jpeg", "webp"][i]}`, sample).sizeBytes).toBe(sample.length);
      for (const ext of ["txt", "stl", "3mf", "step", "gcode"]) expect(() => validate(`disguised.${ext}`, sample)).toThrow("signature");
    });
    for (const ext of ["pdf", "png", "jpg", "webp"]) expect(() => validate(`bad.${ext}`, "text")).toThrow("signature");
  });
  it("records the hash of actual bytes and removes paths and control characters from display filenames", () => {
    const file = validate("../nested/a\u0000.txt", "hello");
    expect(file.filename).toBe("a.txt");
    expect(file.sha256).toBe(createHash("sha256").update("hello").digest("hex"));
  });
  it.each([Buffer.from([0, 1, 2]), Buffer.from([255, 254]), Buffer.from([27, 65])])("requires G-code to be text", (body) => {
    expect(() => validate("bad.gcode", body)).toThrow("text");
  });
});

describe("STL metadata", () => {
  it.each([Buffer.from(ascii), binary()])("extracts identical triangle counts and bounding boxes from ASCII and binary", (bytes) => {
    expect(parseStl(bytes)).toMatchObject({ triangleCount: 1, boundingBox: { min: [-1, 0, -3], max: [3, 4, 2], size: [4, 4, 5] } });
  });
  it("recognises binary files beginning solid, and refuses truncated, inconsistent or non-finite data", () => {
    expect(parseStl(binary()).format).toBe("binary");
    expect(() => parseStl(binary().subarray(0, 133))).toThrow();
    const bytes = binary(); bytes.writeFloatLE(Infinity, 96);
    expect(() => parseStl(bytes)).toThrow("vertex");
    expect(() => parseStl(Buffer.from(ascii.replace("vertex 3 0 2", "")))).toThrow("ASCII");
    expect(() => parseStl(Buffer.from("solid malformed"))).toThrow();
    expect(parseStl(Buffer.from("solid empty\nendsolid empty"))).toMatchObject({ triangleCount: 0, boundingBox: null });
  });
});

describe("G-code slicer metadata", () => {
  it("extracts Prusa time and multiple filament quantities", () => {
    expect(parseGcode(Buffer.from("; generated by PrusaSlicer\n; estimated printing time (normal mode) = 1d 2h 3m 4s\n; filament used [g] = 1.25, 2.5\n; filament used [mm] = 500, 250\nG28")))
      .toMatchObject({ slicer: "PrusaSlicer", estimatedMinutes: (86400 + 7200 + 180 + 4) / 60, filamentGrams: 3.75, filamentLengthMm: 750 });
  });
  it("extracts Cura seconds and metres", () => {
    expect(parseGcode(Buffer.from(";Generated with Cura_SteamEngine\n;TIME:123\n;Filament used: 1.25m")))
      .toMatchObject({ estimatedMinutes: 123 / 60, filamentLengthMm: 1250 });
  });
  it.each(["BambuStudio", "OrcaSlicer"])("extracts %s headers", (slicer) => {
    expect(parseGcode(Buffer.from(`; ${slicer}\n; model printing time: 1h 2m 3s; total estimated time: 1h 5m\n; total filament weight [g] : 12.34\n; total filament length [mm] : 4000`)))
      .toMatchObject({ slicer, estimatedMinutes: 65, filamentGrams: 12.34, filamentLengthMm: 4000 });
  });
  it("leaves absent estimates absent", () => expect(parseGcode(Buffer.from("G28\nG1 X10"))).toEqual({}));
  it("keeps zero durations and ignores malformed or overflowing header numbers", () => {
    expect(parseGcode(Buffer.from("; estimated printing time (normal mode) = 0s"))).toMatchObject({ estimatedMinutes: 0 });
    expect(parseGcode(Buffer.from(`; TIME:${"9".repeat(400)}\n; filament used [g] = 1..2`))).toEqual({});
  });
});
